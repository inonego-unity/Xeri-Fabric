namespace inonego.Xeri.Persistence
{
    // ============================================================
    /// <summary>
    /// 저장된 Record의 데이터 종류와 스키마 계약 정보를 제공한다.
    /// </summary>
    // ============================================================
    public interface IRecordMetadata
    {

    #region 프로퍼티

        // ----------------------------------------------------------------------
        /// <summary>
        /// 데이터 종류 식별자. Document TypeID와 Save SchemaID에 대응한다.
        /// </summary>
        // ----------------------------------------------------------------------
        string TypeID { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 도메인이 정한 데이터 구조 버전.
        /// </summary>
        // ------------------------------------------------------------
        string Version { get; }

    #endregion

    }
}
