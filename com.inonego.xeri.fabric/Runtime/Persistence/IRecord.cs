namespace inonego.Xeri.Persistence
{
    // ============================================================
    /// <summary>
    /// Metadata와 Body를 제공하는 영속 Record의 구조 계약.
    /// </summary>
    /// <typeparam name="TBody">Body 데이터 타입.</typeparam>
    // ============================================================
    public interface IRecord<out TBody>
    {

    #region 프로퍼티

        // ------------------------------------------------------------
        /// <summary>
        /// 기록 종류와 데이터 구조 버전을 포함한 Metadata.
        /// </summary>
        // ------------------------------------------------------------
        IRecordMetadata Metadata { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 기록할 본문 데이터.
        /// </summary>
        // ------------------------------------------------------------
        TBody Body { get; }

    #endregion

    }
}
