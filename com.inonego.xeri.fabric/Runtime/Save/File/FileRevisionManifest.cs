using System;

namespace inonego.Xeri.Save
{
    // ============================================================
    /// <summary>
    /// 하나의 확정된 Revision에서 EntryID와 불변 RecordID의 대응 관계.
    /// </summary>
    // ============================================================
    [Serializable]
    internal sealed class FileRevisionManifest
    {

    #region 내부 데이터

        // ============================================================
        /// <summary>
        /// Manifest에서 한 Entry가 가리키는 불변 기록.
        /// </summary>
        // ============================================================
        [Serializable]
        public sealed class Entry
        {

        #region 필드

            // ------------------------------------------------------------
            /// <summary>
            /// 사용자가 지정한 Entry의 논리 식별자.
            /// </summary>
            // ------------------------------------------------------------
            public string EntryID = string.Empty;

            // ------------------------------------------------------------
            /// <summary>
            /// Record 파일에 부여한 변경 불가능한 식별자.
            /// </summary>
            // ------------------------------------------------------------
            public string RecordID = string.Empty;

            // ------------------------------------------------------------
            /// <summary>
            /// 기록 파일의 SHA-256 해시(소문자 64자리).
            /// </summary>
            // ------------------------------------------------------------
            public string ContentHash = string.Empty;

            // ------------------------------------------------------------
            /// <summary>
            /// 기록 파일의 실제 바이트 크기.
            /// </summary>
            // ------------------------------------------------------------
            public long ByteLength = 0;

        #endregion

        }

    #endregion

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// Manifest 직렬화 형식 버전.
        /// </summary>
        // ------------------------------------------------------------
        public string FormatVersion = string.Empty;

        // ------------------------------------------------------------
        /// <summary>
        /// 이 Revision을 포함하는 Save Scope.
        /// </summary>
        // ------------------------------------------------------------
        public string ScopeID = string.Empty;

        // ------------------------------------------------------------
        /// <summary>
        /// Revision의 불변 식별자.
        /// </summary>
        // ------------------------------------------------------------
        public string RevisionID = string.Empty;

        // ------------------------------------------------------------
        /// <summary>
        /// 이전 확정 RevisionID. 최초 Revision은 빈 문자열이다.
        /// </summary>
        // ------------------------------------------------------------
        public string ParentRevisionID = string.Empty;

        // ------------------------------------------------------------
        /// <summary>
        /// 이 Revision이 생성된 UTC ISO 8601 시각.
        /// </summary>
        // ------------------------------------------------------------
        public string SavedAtUTC = string.Empty;

        // ------------------------------------------------------------
        /// <summary>
        /// Revision에서 접근할 Entry 목록.
        /// </summary>
        // ------------------------------------------------------------
        public Entry[] Entries = Array.Empty<Entry>();

    #endregion

    }
}
