using System;

namespace inonego.Xeri.IO
{
    // ============================================================
    /// <summary>
    /// 읽은 값과 함께 전달되는 외부 리소스의 일회 해제 계약.
    /// </summary>
    // ============================================================
    public interface IReleaseHandle : IDisposable
    {

    #region 프로퍼티

        // ------------------------------------------------------------
        /// <summary>
        /// 외부 리소스 반환이 이미 시도되었는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        bool IsReleased { get; }

    #endregion

    #region 수명

        // ------------------------------------------------------------
        /// <summary>
        /// 보관한 외부 리소스의 사용 권한을 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        void Release();

    #endregion

    }
}
